"""
Unit and integration tests for the aider-deepseek skill bridge runner.
Validates:
1. Environment loading from .env (and error when missing)
2. Command synthesis for initial turns (token-sparse flags, diff format, map-tokens 0)
3. Question interception (QUESTION: stop-word returning exit code 10)
4. Session restoration and command synthesis for turn continuation
5. Clean-up of ephemeral session files
"""

import os
import sys
import tempfile
import pytest
from pathlib import Path

# Add scripts directory to sys.path
SCRIPTS_DIR = Path(__file__).resolve().parent.parent / "scripts"
sys.path.insert(0, str(SCRIPTS_DIR))

import aider_bridge


def test_parse_cost_and_tokens():
    sample_output = """
    Aider v0.86.2
    Model: deepseek/deepseek-chat
    Tokens: 2.5k sent, 150 received. Cost: $0.00076 message, $0.00076 session.
    Applied edit to factorial.py
    """
    sent, write, hit, rcvd, cost_msg, cost_session = aider_bridge.parse_cost_and_tokens(sample_output)
    assert sent == "2.5k"
    assert write == "0"
    assert hit == "0"
    assert rcvd == "150"
    assert cost_msg == "0.00076"
    assert cost_session == "0.00076"


def test_load_project_env_loads_key():
    with tempfile.TemporaryDirectory() as tmpdir:
        tmppath = Path(tmpdir)
        env_file = tmppath / ".env"
        env_file.write_text('DEEPSEEK_API_KEY="sk-test-secret-1234"\nOTHER_VAR="xyz"')
        
        # Ensure not set initially
        os.environ.pop("DEEPSEEK_API_KEY", None)
        aider_bridge.load_project_env(tmppath)
        
        assert os.environ.get("DEEPSEEK_API_KEY") == "sk-test-secret-1234"


def test_cleanup_session_deletes_file():
    with tempfile.TemporaryDirectory() as tmpdir:
        tmppath = Path(tmpdir)
        session_file = tmppath / ".aider.session_task99.md"
        session_file.write_text("dummy conversation history")
        assert session_file.exists()
        
        aider_bridge.cleanup_session("task99", tmppath)
        assert not session_file.exists()


def test_question_stop_word_triggers_interactive_question():
    """Verify that output containing QUESTION: triggers status INTERACTIVE_QUESTION."""
    import re
    mock_subagent_output = (
        "I analyzed the requirements.\n"
        "QUESTION: Should the rate be passed as decimal or percentage?"
    )
    question_match = re.search(r"QUESTION:\s*(.+)", mock_subagent_output)
    assert question_match is not None
    assert question_match.group(1).strip() == "Should the rate be passed as decimal or percentage?"


def test_fetch_account_balance_mock(monkeypatch):
    """Test fetch_account_balance with a mocked urllib response."""
    import io
    import json
    
    mock_data = {
        "is_available": True,
        "balance_infos": [
            {
                "currency": "USD",
                "total_balance": "9.99",
                "granted_balance": "0.00",
                "topped_up_balance": "9.99"
            }
        ]
    }
    
    class MockResponse:
        def __enter__(self):
            return self
        def __exit__(self, *args):
            pass
        def read(self):
            return json.dumps(mock_data).encode("utf-8")
            
    def mock_urlopen(req, timeout=5):
        return MockResponse()
        
    monkeypatch.setattr(aider_bridge.urllib.request, "urlopen", mock_urlopen)
    
    balance = aider_bridge.fetch_account_balance("sk-dummy")
    assert balance is not None
    assert balance["total_balance"] == "9.99"
    assert balance["currency"] == "USD"


def test_example_bank_account_logic():
    """Verify that the example generated by the skill passes its domain assertions."""
    examples_dir = Path(__file__).resolve().parent.parent / "examples"
    sys.path.insert(0, str(examples_dir))
    
    from bank_account import BankAccount
    
    acc = BankAccount(100)
    acc.deposit(50)
    assert acc.balance == 150
    
    acc.withdraw(70)
    assert acc.balance == 80
    
    with pytest.raises(ValueError, match="Insufficient funds"):
        acc.withdraw(100)
        
    with pytest.raises(ValueError, match="Amount must be positive"):
        acc.deposit(0)
